def _entry_line(entry) -> dict:
    return json.loads(encode_mutation(EntryMutation(entry=entry, lane="main")))


def _assistant(content: list, **kwargs) -> AssistantMessage:
    return AssistantMessage(api="chat", provider="anthropic", model="claude", content=content, timestamp=2000, **kwargs)


def _round_trip_entry(entry):
    mutation = EntryMutation(entry=entry, lane="main")
    decoded = decode_mutation(encode_mutation(mutation))
    assert decoded == mutation
    return decoded.entry


def _round_trip_record(record):
    mutation = RecordMutation(record=record)
    decoded = decode_mutation(encode_mutation(mutation))
    assert decoded == mutation
    return decoded.record


