def test_decodes_hand_written_name_fact_with_absent_key_clears_name() -> None:
    # TS writes `{ kind: "fact", seq, fact: "name" }` (key omitted, not
    # `name: null`) to mean "clear the session name". `JSON.stringify` drops
    # `undefined` values, so an absent key -- not an explicit `null` -- is the
    # wire representation of "no name".
    line = '{"kind":"fact","seq":8,"fact":"name"}'
    mutation = decode_mutation(line)
    assert isinstance(mutation, NameFactMutation)
    assert mutation.name is None


def test_rejects_name_fact_with_explicit_null_name() -> None:
    # TS's parser does `typeof value.name !== "string"` and rejects an
    # explicit `null` even though it accepts an absent key; verify this port
    # keeps that same asymmetry rather than silently accepting `null`.
    line = '{"kind":"fact","seq":9,"fact":"name","name":null}'
    try:
        decode_mutation(line)
    except JsonlDecodeError:
        pass
    else:
        raise AssertionError("expected JsonlDecodeError for explicit null name")


