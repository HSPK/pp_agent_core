def test_encoded_lines_stay_single_line_for_multiline_and_unicode_text() -> None:
    # JSONL framing depends on the encoder escaping every embedded newline; a
    # raw newline in a message would split one entry across two log lines.
    text = 'line one\nline two\ttabbed "quoted" \\ backslash \r\nemoji 🙂 中文'
    entry = MessageEntry(id="e1", message=UserMessage(content=text, timestamp=1), parent_id=None, seq=1, timestamp=1)

    line = encode_mutation(EntryMutation(entry=entry, lane="main"))

    assert line.endswith("\n")
    assert line.count("\n") == 1
    assert "\r" not in line[:-1]
    assert decode_mutation(line).entry.message.content == text


def test_decodes_unicode_written_without_escape_sequences() -> None:
    # `JSON.stringify` leaves non-ASCII characters raw, so a TypeScript-written
    # line contains the literal characters rather than \uXXXX escapes.
    line = json.dumps(
        {
            "kind": "entry",
            "lane": "main",
            "type": "message",
            "id": "e1",
            "message": {"role": "user", "content": "héllo 🙂 中文", "timestamp": 1},
            "parentId": None,
            "seq": 1,
            "timestamp": 1,
        },
        ensure_ascii=False,
    )

    assert "🙂" in line
    assert decode_mutation(line).entry.message.content == "héllo 🙂 中文"


