def test_decodes_hand_written_header_line() -> None:
    line = (
        '{"kind":"header","version":4,"id":"sess-1","createdAt":1700000000000,'
        '"cwd":"/home/user/project","parentSessionId":"sess-0",'
        '"metadata":{"origin":"cli"}}'
    )
    header = decode_header(line)
    assert header.id == "sess-1"
    assert header.created_at == 1700000000000
    assert header.cwd == "/home/user/project"
    assert header.parent_session_id == "sess-0"
    assert header.legacy_parent_session_path is None
    assert header.metadata == {"origin": "cli"}


